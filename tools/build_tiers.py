#!/usr/bin/env python3
"""Regenerate config/tiers/*.conf and workflows/tiers/<tier>/ from tiers_spec.py.

    python3 tools/build_tiers.py            # network: checks every URL + size
    python3 tools/build_tiers.py --offline  # reuse tools/tier_sizes.json

Run it after editing tools/tiers_spec.py or any bundled workflow, then commit
the generated files. The image does not run this; provision.sh only reads the
generated .conf files.
"""
import json, os, re, sys, urllib.request, urllib.error

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from tiers_spec import TIERS, COMMON, WORKFLOW_NAMES  # noqa: E402

SIZES_JSON = os.path.join(ROOT, "tools", "tier_sizes.json")
OFFLINE = "--offline" in sys.argv


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


def hf_size(url):
    req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "curl/8.5.0"})
    tok = os.environ.get("HF_TOKEN")
    if tok:
        req.add_header("Authorization", f"Bearer {tok}")
    op = urllib.request.build_opener(NoRedirect)
    try:
        r = op.open(req, timeout=60)
        code, hdr = r.status, r.headers
    except urllib.error.HTTPError as e:
        code, hdr = e.code, e.headers
    if code not in (200, 302, 307):
        raise SystemExit(f"URL check failed ({code}): {url}")
    size = hdr.get("x-linked-size") or hdr.get("content-length")
    return int(size)


def civ_size(vid, name):
    req = urllib.request.Request(f"https://civitai.com/api/v1/model-versions/{vid}",
                                 headers={"User-Agent": "curl/8.5.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        meta = json.load(r)
    for f in meta.get("files", []):
        if f.get("name") == name:
            return int(f["sizeKB"] * 1024)
    raise SystemExit(f"CivitAI {vid} has no file named {name}")


def gb(n):
    return f"{n / 1e9:.2f} GB"


sizes = json.load(open(SIZES_JSON)) if os.path.exists(SIZES_JSON) else {}


def size_of(entry):
    key = entry["url"] + ("#" + entry["name"] if entry.get("civitai") else "")
    if key not in sizes:
        if OFFLINE:
            raise SystemExit(f"--offline but no cached size for {key}")
        sizes[key] = civ_size(entry["civitai"], entry["name"]) if entry.get("civitai") else hf_size(entry["url"])
    return sizes[key]


ORDER = ["image", "ref2va", "fl2va", "te", "te9b", "video_vae", "audio_vae", "image_vae",
         "turbo_ref2v", "turbo_fl2v", "pdmd_lora", "controlnet", "sdpose", "sdpose_det", "eros"]
WHY = {
    "image": "MiniMax H3 Image diffusion model (t2i / edit / your multi-photo workflows)",
    "ref2va": "H3 video ref2va (R2V, multiframe, ControlNet, Multishot chains)",
    "fl2va": "H3 video fl2va (T2V, I2V, first/last frame)",
    "te": "Qwen3-VL 32B text encoder (CLIPLoader type minimax) - image AND video",
    "te9b": "Qwen3.5 9B prompt enhancer (TextGenerateV2 in the image workflows)",
    "video_vae": "video VAE", "audio_vae": "audio VAE (required by every video graph)",
    "image_vae": "image VAE",
    "turbo_ref2v": "ref2v 4-step turbo LoRA (pairs with ref2va ONLY)",
    "turbo_fl2v": "fl2v 8-step turbo LoRA (pairs with fl2va ONLY)",
    "pdmd_lora": "H3 Image pDMD 2-step speed LoRA (LoraLoaderModelOnly, strength 1.0, 2 steps)",
    "controlnet": "Fun ControlNet Union patch (video_minimax_h3_fun_controlnet_union)",
    "sdpose": "SDPose whole-body pose model (ControlNet template)",
    "sdpose_det": "RT-DETR person detector for SDPose (ControlNet template)",
    "eros": "H3 Eros Max beta7 NSFW 8-step merge (CivitAI; needs CIVITAI_API_TOKEN)",
}

summary = {}
os.makedirs(os.path.join(ROOT, "config", "tiers"), exist_ok=True)
for tier, spec in TIERS.items():
    roles = dict(spec["roles"]); roles.update(COMMON)
    seen, lines, total = set(), [], 0
    for role in ORDER:
        e = roles[role]
        if e["name"] in seen:
            continue
        seen.add(e["name"])
        s = size_of(e); total += s
        lines.append(f"# {WHY[role]}  [{gb(s)}]")
        if e.get("civitai"):
            lines.append(f"{e['cat']} | {e['url']} | {e['name']}")
        else:
            lines.append(f"{e['cat']} | {e['url']}")
    summary[tier] = {"label": spec["label"], "gpus": spec["gpus"], "total_bytes": total,
                     "files": {r: roles[r]["name"] for r in ORDER},
                     "sizes": {roles[r]["name"]: size_of(roles[r]) for r in ORDER}}
    hdr = [
        "# " + "=" * 76,
        f"#  GPU TIER {tier}: {spec['label']}",
        f"#  Typical RunPod GPUs: {spec['gpus']}",
        f"#  Auto-picked when the GPU reports >= {spec['vram_min_mib']} MiB (H3_TIER=auto).",
        f"#  TOTAL DOWNLOAD: {gb(total)} (+ LoRA catalogs, see README)",
        "#",
        "#  GENERATED by tools/build_tiers.py from tools/tiers_spec.py - edit the spec,",
        "#  not this file. Format is the same as models.conf:  <folder> | <url> | [file]",
        "#  A civitai-version line with a file name downloads THAT file of the version.",
        "# " + "=" * 76,
        "",
    ]
    with open(os.path.join(ROOT, "config", "tiers", f"{tier}.conf"), "w") as f:
        f.write("\n".join(hdr + lines) + "\n")

json.dump(sizes, open(SIZES_JSON, "w"), indent=1, sort_keys=True)

# ---------------------------------------------------------------- workflows
URL_RE = re.compile(r'https://huggingface\.co/[^"\s)\]]*/(' + "|".join(map(re.escape, WORKFLOW_NAMES)) + r')(?=["\s)\]])')
NAME_RE = re.compile("|".join(map(re.escape, sorted(WORKFLOW_NAMES, key=len, reverse=True))))
SRC = [("", os.path.join(ROOT, "workflows")), ("official", os.path.join(ROOT, "workflows", "official"))]
report = {}
for tier, spec in TIERS.items():
    roles = dict(spec["roles"]); roles.update(COMMON)
    out_root = os.path.join(ROOT, "workflows", "tiers", tier)
    for sub, src in SRC:
        out = os.path.join(out_root, sub)
        os.makedirs(out, exist_ok=True)
        for fn in sorted(os.listdir(src)):
            if not fn.endswith(".json"):
                continue
            text = open(os.path.join(src, fn), encoding="utf-8").read()
            text = URL_RE.sub(lambda m: roles[WORKFLOW_NAMES[m.group(1)]]["url"]
                              if not roles[WORKFLOW_NAMES[m.group(1)]].get("civitai") else m.group(0), text)
            text = NAME_RE.sub(lambda m: roles[WORKFLOW_NAMES[m.group(0)]]["name"], text)
            json.loads(text)  # must still be valid JSON
            open(os.path.join(out, fn), "w", encoding="utf-8").write(text)
    tier_files = {roles[r]["name"] for r in roles}
    report[tier] = tier_files
    with open(os.path.join(out_root, "README.md"), "w") as f:
        f.write(f"# Workflows for GPU tier {tier}\n\n{spec['label']}.\n\n"
                "Generated by `tools/build_tiers.py`: the same graphs as `workflows/` and "
                "`workflows/official/`, with only the model file names (and their download "
                "URLs) switched to this tier's files:\n\n"
                + "\n".join(f"- {r}: `{roles[r]['name']}`" for r in ORDER) + "\n")

with open(os.path.join(ROOT, "tools", "tier_summary.json"), "w") as f:
    json.dump(summary, f, indent=1)
for t, s in summary.items():
    print(f"tier {t:>2}: {gb(s['total_bytes'])}  {s['label']}")
